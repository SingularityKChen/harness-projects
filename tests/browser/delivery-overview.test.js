test('delivery overview opens unique drawer and returns keyboard focus', {timeout:60000}, async t=>{
  const h=await startExecutionServer({seed:'read'})
  const browser=await chromium.launch()
  const context=await browser.newContext(),page=await context.newPage(),errors=[],outside=[]
  page.setDefaultTimeout(7000);await mkdir(evidence,{recursive:true});await context.tracing.start({screenshots:true,snapshots:true})
  t.after(async()=>{await context.tracing.stop({path:evidence+'/trace.zip'});await page.evaluate(()=>window.fixture?.unmount()).catch(()=>{});await context.close();await browser.close();await h.close()})
  await context.route('**/*',route=>{if(new URL(route.request().url()).origin===h.url)return route.continue();outside.push(route.request().url());return route.abort()})
  page.on('pageerror',e=>errors.push(e.message));await page.goto(h.url)
  const mode=page.getByRole('button',{name:'工程交付',exact:true});await mode.waitFor();await page.getByRole('searchbox',{name:'搜索标题或编号'}).fill('issue-1');await tabTo(page,mode);await page.keyboard.press('Enter')
  const overview=page.getByRole('region',{name:'工程交付总览',exact:true})
  await overview.getByText('本页已刷新',{exact:true}).waitFor()
  assert.equal(await mode.evaluate(el=>el===document.activeElement),true,'mode switch preserves button focus')
  assert.equal(h.requests.filter(r=>r.name==='refreshDeliveryFacts').length,3)
  await overview.getByRole('button',{name:'刷新本页交付',exact:true}).click();await overview.getByText('本页已刷新',{exact:true}).waitFor()
  assert.equal(h.requests.filter(r=>r.name==='refreshDeliveryFacts').length,6)
  for(const item of h.requests.filter(r=>r.name==='refreshDeliveryFacts')){const index=h.requests.indexOf(item);assert.ok(h.requests.slice(index+1).some(r=>r.name==='getDeliveryProjection'&&r.input.workItemId===item.input.workItemId&&r.input.repositoryId===item.input.repositoryId))}
  assert.equal(await overview.getByRole('searchbox').count(),0);assert.equal(await overview.locator('.hp-table-controls,.hp-column-tools').count(),0)
  assert.equal(await overview.locator('article').count(),3);assert.equal(await overview.getByText('规划项 draft-1',{exact:true}).count(),0)
  assert.ok(await overview.locator('[data-position="change_request"] [data-reason]').count()>0)
  assert.equal(await overview.locator('[data-state="passed"]').count(),0)
  const title=overview.getByRole('link',{name:'规划项 issue-1',exact:true});await tabTo(page,title);await page.keyboard.press('Enter')
  assert.equal(await page.getByRole('dialog').count(),1);await page.keyboard.press('Escape');await page.getByRole('dialog').waitFor({state:'detached'})
  assert.equal(await title.evaluate(el=>el===document.activeElement),true)
  await page.screenshot({path:evidence+'/wide.png',fullPage:true})
  await page.setViewportSize({width:320,height:800});await page.evaluate(()=>document.documentElement.style.fontSize='30px')
  assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),true)
  await page.screenshot({path:evidence+'/narrow-200.png',fullPage:true})
  const before=h.requests.filter(r=>r.name==='refreshDeliveryFacts').length
  await page.evaluate(()=>window.dispatchEvent(new PageTransitionEvent('pageshow')))
  await overview.getByText('本页已刷新',{exact:true}).waitFor();assert.equal(h.requests.filter(r=>r.name==='refreshDeliveryFacts').length,before)
  await title.click();await page.getByRole('dialog').waitFor()
  await page.evaluate(()=>window.fixture.command('permission',{domain:'planning',key:'planning.item.read',enabled:false}))
  await fetch(h.url+'/remote',{method:'POST',body:JSON.stringify({name:'refreshPlanning',input:{actorRef:{kind:'user'}}})})
  await overview.getByText('无法读取工作项，确认授权后重试',{exact:true}).waitFor()
  await page.keyboard.press('Escape');await page.getByRole('dialog').waitFor({state:'detached'})
  assert.equal(await overview.getByRole('heading',{name:'工程交付',exact:true}).evaluate(el=>el===document.activeElement),true)
  const state=await page.evaluate(()=>window.fixture.command('inspect'))
  assert.ok(Object.entries(state.calls).filter(([key])=>key.startsWith('write:')).every(([,count])=>count===0))
  assert.deepEqual(errors,[]);assert.deepEqual(outside,[])
})

test('production Host overview preserves missing failed unknown and fresh CI facts on one page', {timeout:60000}, async t=>{
  const h=await startExecutionServer({seed:'overview'}),browser=await chromium.launch(),context=await browser.newContext({timezoneId:'Asia/Singapore'}),page=await context.newPage()
  page.setDefaultTimeout(5000);await mkdir(evidence,{recursive:true});await context.tracing.start({screenshots:true,snapshots:true})
  t.after(async()=>{await fetch(h.url+'/control',{method:'POST',body:JSON.stringify({action:'release'})});await context.tracing.stop({path:evidence+'/facts-trace.zip'});await page.evaluate(()=>window.fixture?.unmount()).catch(()=>{});await context.close();await browser.close();await h.close()})
  await context.route('**/*',route=>new URL(route.request().url()).origin===h.url?route.continue():route.abort())
  const originalPlanning=await planningFacts(h)
  await page.goto(h.url);await page.getByRole('button',{name:'工程交付',exact:true}).click()
  const overview=page.getByRole('region',{name:'工程交付总览',exact:true})
  await overview.getByText('本页已刷新',{exact:true}).waitFor()
  const row=title=>overview.locator('article').filter({has:page.getByRole('link',{name:title,exact:true})})
  assert.equal(await overview.locator('article').count(),4)
  assert.ok(await row('规划项 issue-1').locator('[data-state="passed"]').count()>0)
  assert.ok(await row('规划项 issue-2').locator('[data-state="failed"]').count()>0)
  assert.ok(await row('规划项 issue-4').locator('[data-state="unknown"]').count()>0)
  assert.ok(await row('Overview gap').locator('[data-position="change_request"] [data-reason]').count()>0)
  assert.equal(await row('Overview gap').locator('[data-state="passed"]').count(),0)
  const confirmed=(await h.installed.service.getDeliveryProjection(h.itemId,'repo-alpha')).projection.freshness.find(set=>set.kind==='check_run').confirmedAt
  const observed=row('规划项 issue-1').locator('[data-position=check_run] time')
  assert.equal(await observed.getAttribute('datetime'),confirmed);assert.match(await observed.textContent(),/Asia\/Singapore/);assert.doesNotMatch(await observed.textContent(),/T\d{2}:|\.\d{3}Z/)
  await page.screenshot({path:evidence+'/facts-wide.png',fullPage:true})
  await row('规划项 issue-1').scrollIntoViewIfNeeded();await page.screenshot({path:evidence+'/facts-fresh-wide.png'})
  await row('Overview gap').scrollIntoViewIfNeeded();await page.screenshot({path:evidence+'/facts-gap-wide.png'})
  await page.setViewportSize({width:320,height:800});await page.evaluate(()=>document.documentElement.style.fontSize='30px')
  assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),true)
  await page.screenshot({path:evidence+'/facts-narrow-200.png',fullPage:true})
  await observed.scrollIntoViewIfNeeded();await page.screenshot({path:evidence+'/facts-row-narrow-200.png'})
  assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),true)
  assert.deepEqual(await planningFacts(h),originalPlanning,'overview refresh leaves planning facts unchanged')
  await page.evaluate(()=>window.fixture.command('hold',{domain:'delivery',method:'listChecks',enabled:true}))
  await overview.getByRole('button',{name:'刷新本页交付',exact:true}).click()
  const held=async()=>await page.evaluate(()=>window.fixture.command('inspect'))
  for(let i=0;i<100&&!(await held()).held;i++)await new Promise(resolve=>setTimeout(resolve,10))
  assert.ok((await held()).held>0)
  await page.evaluate(()=>window.fixture.command('permission',{domain:'planning',key:'planning.item.read',enabled:false}))
  await fetch(h.url+'/remote',{method:'POST',body:JSON.stringify({name:'refreshPlanning',input:{actorRef:{kind:'user'}}})})
  await overview.getByText('无法读取工作项，确认授权后重试',{exact:true}).waitFor()
  await page.evaluate(()=>window.fixture.command('release'))
  await overview.getByText('无法读取工作项，确认授权后重试',{exact:true}).waitFor()
  assert.equal(await overview.locator('article').count(),0);assert.doesNotMatch(await overview.textContent(),/Overview gap|issue-1|ci-overview/)
  const state=await held();assert.ok(Object.entries(state.calls).filter(([key])=>key.startsWith('write:planning')).every(([,count])=>count===0))
})
